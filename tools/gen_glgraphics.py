#!/usr/bin/env python3
"""원본(디컴파일) GLGraphics.java → 웹용 GLGraphics.java + GLWeb.java 생성.
모든 native 인스턴스 메서드를 GLWeb의 static native(고유 이름)로 위임한다.
JS는 GLWeb 쪽 이름(Java_keel_gfx_GLWeb_<name>)으로 구현한다.
"""
import re, sys
src, out_dir = sys.argv[1], sys.argv[2]
text = open(src).read()
SUFFIX = {'byte[]':'B','char[]':'C','short[]':'S','int[]':'I','float[]':'F','double[]':'D','boolean[]':'Z','long':'J','Object':'O','String':'T'}
nat_re = re.compile(r'^(\s*)((?:public|private|protected)?\s*(?:static\s+)?(?:final\s+)?)native\s+([\w\[\]]+)\s+(\w+)\(([^)]*)\);', re.M)
glweb = []
names = {}
def repl(m):
    indent, mods, ret, name, params = m.groups()
    static = 'static' in mods
    plist = [p.strip() for p in params.split(',') if p.strip()]
    types = [re.sub(r'\s+\w+$', '', p) for p in plist]
    args = [p.split()[-1] for p in plist]
    # 고유 이름: 같은 이름이 여러 개면 마지막 파라미터 타입 접미사
    count = len(re.findall(r'\bnative\s+[\w\[\]]+\s+' + re.escape(name) + r'\(', text))
    uname = name
    if count > 1:
        uname = name + '_' + SUFFIX.get(types[-1], types[-1].replace('[]', 'A'))
    if uname in names:
        uname = uname + '_' + str(len(names))
    names[uname] = True
    glweb.append(f'    static native {ret} {uname}({", ".join(types[i] + " a" + str(i) for i in range(len(types)))});')
    call = f'GLWeb.{uname}({", ".join(args)})'
    body = f'{indent}{mods.strip()} {ret} {name}({params}) {{ {"return " if ret != "void" else ""}{call}; }}'
    return body
out = nat_re.sub(repl, text)
# static 초기화의 loadLibrary 제거: 블록 전체를 단순화
out = re.sub(r'    static \{\n        try \{\n            AccessController\.doPrivileged.*?\n        colorptr = null;', '    static {\n        colorptr = null;', out, flags=re.S)
# 포인터 래퍼: NativeArray 의 실제 배열을 넘긴다
for fn, nat in [('glColorPointer','_glColorPointer'),('glEdgeFlagPointer','_glEdgeFlagPointer'),('glIndexPointer','_glIndexPointer'),('glNormalPointer','_glNormalPointer'),('glTexCoordPointer','_glTexCoordPointer'),('glInterleavedArrays','_glInterleavedArrays'),('glVertexPointer','_glVertexPointer'),('glSecondaryColorPointerEXT','_glSecondaryColorPointerEXT')]:
    out = out.replace(f'nativeArray.nativePointer', 'nativeArray.nativePointer')
for kind, fn in [(0,'glVertexPointer'),(1,'glTexCoordPointer'),(2,'glColorPointer'),(3,'glNormalPointer')]:
    out = re.sub(r'this\._' + fn + r'\((\w+), nativeArray\.type, (\w+), nativeArray\.nativePointer\);',
                 f'GLWeb.arrayPointer({kind}, \\1, nativeArray.type, \\2, nativeArray.data);', out)
    out = re.sub(r'this\._' + fn + r'\((\w+), nativeArray\.type, (\w+), 0L\);',
                 f'GLWeb.arrayPointer({kind}, \\1, 0, \\2, null);', out)
out = out.replace('import keel.gfx.NativeArray;', 'import keel.gfx.NativeArray;\n// GENERATED by tools/gen_glgraphics.py (web port)')
open(f'{out_dir}/GLGraphics.java', 'w').write(out)
open(f'{out_dir}/GLWeb.java', 'w').write('package keel.gfx;\n\n/** GENERATED: GLGraphics 의 모든 네이티브를 고유 이름의 static native 로 모은 클래스. JS가 Java_keel_gfx_GLWeb_* 로 구현. */\npublic final class GLWeb {\n    private GLWeb() {}\n' + '\n'.join(glweb) + '\n    /** 포인터 계열: NativeArray 실체 배열을 직접 넘긴다. */\n    static native void arrayPointer(int kind, int size, int type, int stride, Object data);\n}\n')
print('natives:', len(glweb))
